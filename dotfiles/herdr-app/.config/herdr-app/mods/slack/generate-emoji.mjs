// Writes emoji-data.js: every standard Slack emoji with all its names, grouped
// by Unicode subgroup. Slack's names come from emoji-datasource (iamcal's data,
// which Slack uses); the labels are Unicode's CLDR short names, joined by
// character. Run `node generate-emoji.mjs` in this folder after raising the
// two pinned versions.
import { writeFileSync } from "node:fs";

const DATASOURCE = "https://cdn.jsdelivr.net/npm/emoji-datasource@16.0.0/emoji.json";
const EMOJI_TEST = "https://www.unicode.org/Public/emoji/16.0/emoji-test.txt";
const COUNTRY_SUBGROUPS = new Set(["country-flag", "subdivision-flag"]);
const OUTPUT = new URL("./emoji-data.js", import.meta.url);

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} answered ${r.status}`);
  return r;
};
const data = await (await get(DATASOURCE)).json();
const test = await (await get(EMOJI_TEST)).text();

// CLDR short name by codepoints, for every fully-qualified emoji.
const labels = new Map();
for (const line of test.split("\n")) {
  const match = line.match(/^([0-9A-F ]+?)\s*; fully-qualified\s+# \S+ E\d+\.\d+ (.+)$/);
  if (match) labels.set(match[1].replace(/ /g, "-"), match[2].trim());
}

const categories = new Map();
const countries = [];
const missing = [];
for (const e of [...data].sort((a, b) => a.sort_order - b.sort_order)) {
  if (e.category === "Component") continue;
  const label = labels.get(e.unified);
  if (!label) {
    missing.push(e.short_name);
    continue;
  }
  const char = String.fromCodePoint(...e.unified.split("-").map((h) => parseInt(h, 16)));
  const entry = { char, label, names: e.short_names };
  if (COUNTRY_SUBGROUPS.has(e.subcategory)) {
    countries.push({ ...entry, label: label.replace(/^flag: /, "") });
    continue;
  }
  if (!categories.has(e.subcategory)) categories.set(e.subcategory, []);
  categories.get(e.subcategory).push(entry);
}
if (missing.length) throw new Error(`No CLDR name for ${missing.join(", ")}`);
countries.sort((a, b) => a.label.localeCompare(b.label, "en"));

const line = (e) => `    ${JSON.stringify(e)},`;
const source = [
  "// Generated by generate-emoji.mjs from emoji-datasource and Unicode's",
  "// emoji-test.txt; don't edit. names[0] is Slack's canonical name.",
  "",
  "export const CATEGORIES = [",
  ...[...categories].flatMap(([key, emoji]) => [
    `  { label: ${JSON.stringify(key.replace(/-/g, ": ").replace(/ & /g, " and "))}, emoji: [`,
    ...emoji.map(line),
    "  ] },",
  ]),
  "];",
  "",
  "export const COUNTRIES = [",
  ...countries.map((e) => line(e).slice(2)),
  "];",
  "",
].join("\n");
writeFileSync(OUTPUT, source);
const total = [...categories.values()].reduce((n, e) => n + e.length, 0);
console.log(`${categories.size} categories, ${total} emoji, ${countries.length} country flags`);
